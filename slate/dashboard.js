/* Browser-time status: stored observations are never represented as real-time odds. */
'use strict';
const root = document.querySelector('[data-root-overview]');
const base = root ? 'slate/' : '';
const parseTime = value => {
  if (typeof value !== 'string' || !/(Z|[+-]\d\d:\d\d)$/.test(value)) return NaN;
  return Date.parse(value);
};
function refreshRowState(capture) {
  const now = Date.now(), stale = !Number.isFinite(capture) || now - capture > 6 * 3600000 || capture > now;
  for (const row of document.querySelectorAll('.fixture-row')) {
    const lock = parseTime(row.dataset.lock), quote = parseTime(row.dataset.quote), rowCapture = parseTime(row.dataset.captured);
    const cell = row.querySelector('.pick-cell');
    if (!cell) continue;
    if (!cell.dataset.original) cell.dataset.original = cell.innerHTML;
    if (!Number.isFinite(lock) || lock <= now) cell.textContent = 'Locked / time unverified — no active pick';
    else if (stale || !Number.isFinite(rowCapture) || now - rowCapture > 6 * 3600000 || rowCapture > now || (row.dataset.quote && (!Number.isFinite(quote) || now - quote > 6 * 3600000 || quote > now))) cell.textContent = 'Stale / time unverified — no active pick';
    else cell.innerHTML = cell.dataset.original; // Original escaped markup generated by our builder.
  }
}
async function update() {
  const banner = document.getElementById('freshness');
  try {
    const res = await fetch(base + 'data/analysis.json', {cache: 'no-store'});
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    const data = await res.json(), t = parseTime(data.summary?.generated_utc), now = Date.now();
    if (!Number.isFinite(t) || !Array.isArray(data.fixtures) || !Array.isArray(data.analysis)) throw new Error('snapshot schema / capture time invalid');
    const stale = now - t > 6 * 3600000 || t > now;
    if (banner) banner.textContent = `${stale ? 'STALE / REVIEW' : 'Published observation'} · Captured ${data.summary.generated_utc} · ${Math.max(0, Math.floor((now-t)/60000))} minutes ago. Odds are not live; scheduled checks can fail or be delayed.`;
    refreshRowState(t);
    if (root) {
      const cs = data.fixtures.filter(r => r.sport === 'cs2');
      const open = cs.filter(r => parseTime(r.lock_utc) > now);
      const active = data.analysis.filter(r => r.sport === 'cs2' && parseTime(r.lock_utc) > now);
      const values = {'cs-count': cs.length, 'open-count': open.length, 'market-count': stale ? '—' : active.filter(r => r.market_p_a_pct != null && now - parseTime(r.market_captured_utc) <= 6 * 3600000).length, 'pick-count': stale ? '—' : active.filter(r => r.pick).length};
      for (const [id, value] of Object.entries(values)) { const el = document.getElementById(id); if (el) el.textContent = value; }
    }
  } catch (error) {
    if (banner) banner.textContent = `Snapshot unavailable (${error.message}). Coverage / freshness unverified; no values substituted.`;
    refreshRowState(NaN);
    for (const id of ['cs-count','open-count','market-count','pick-count']) { const el = document.getElementById(id); if (el) el.textContent = '—'; }
  }
}
for (const input of document.querySelectorAll('.table-search input')) {
  input.addEventListener('input', () => {
    const table = input.closest('label').nextElementSibling;
    for (const row of table.querySelectorAll('.fixture-row')) row.hidden = !row.textContent.toLowerCase().includes(input.value.toLowerCase().trim());
  });
}
update();
setInterval(update, 60000);
