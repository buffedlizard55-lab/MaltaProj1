def process_matches():
    os.makedirs("data", exist_ok=True)
    processed = []
    
    for m in MATCHES_DATA:
        # 1. Devig bookmaker lines if available
        if m["bookmaker_odds1"] and m["bookmaker_odds2"]:
            p_mkt1, p_mkt2 = devig_twoway(m["bookmaker_odds1"], m["bookmaker_odds2"])
        else:
            p_mkt1, p_mkt2 = None, None
            
        # 2. Originate independent win probabilities
        p_orig1, p_orig2 = originate_cs2_probability(
            rank1=m["team1_rank"],
            rank2=m["team2_rank"],
            vrs1=m["team1_vrs"],
            vrs2=m["team2_vrs"],
            winrate1=0.55,
            winrate2=0.50,
            format_type=m["format"]
        )
        
        orig_line1 = prob_to_fair_odds(p_orig1)
        orig_line2 = prob_to_fair_odds(p_orig2)
        
        # 3. Value Edge analysis
        edge1 = round(p_orig1 - p_mkt1, 1) if p_mkt1 is not None else None
        edge2 = round(p_orig2 - p_mkt2, 1) if p_mkt2 is not None else None
        
        # Hotspawn skew vs reality
        hotspawn_diff1 = round(m["hotspawn_pick1_pct"] - (p_mkt1 if p_mkt1 is not None else p_orig1), 1)
        
        item = {
            **m,
            "market_prob1_pct": p_mkt1,
            "market_prob2_pct": p_mkt2,
            "originated_prob1_pct": p_orig1,
            "originated_prob2_pct": p_orig2,
            "originated_odds1": orig_line1,
            "originated_odds2": orig_line2,
            "edge1_pct": edge1,
            "edge2_pct": edge2,
            "hotspawn_bias1_pct": hotspawn_diff1
        }
        processed.append(item)
        
    with open("data/matches.json", "w", encoding="utf-8") as f:
        json.dump(processed, f, indent=2)
        
    keys = list(processed[0].keys())
    with open("data/matches_hub_2cb6bff4.csv", "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=keys)
        writer.writeheader()
        writer.writerows(processed)
        
    print(f"Successfully compiled {len(processed)} matches into data/matches.json and data/matches_hub_2cb6bff4.csv")

if __name__ == "__main__":
    process_matches()
