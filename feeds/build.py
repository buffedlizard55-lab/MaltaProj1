#!/usr/bin/env python3
"""Render feeds/index.html, feeds/flagged.html and feeds/method.html from feeds/data/.

Session arena/a0bdf924.  Self-contained HTML (one local stylesheet, a few lines of inline JS
that only convert UTC times to the viewer's local time).  No third-party scripts or fonts.
"""
from __future__ import annotations

import csv
import html
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
DATA = HERE / "data"
REPO_URL = "https://github.com/buffedlizard55-lab/MaltaProj1"
RUNS_URL = f"{REPO_URL}/actions/workflows/feed-a0bdf924.yml"


def esc(x) -> str:
    return html.escape("" if x is None else str(x), quote=True)


def read_csv(name: str) -> list[dict]:
    path = DATA / name
    if not path.exists():
        return []
    with path.open(encoding="utf-8", newline="") as fh:
        return list(csv.DictReader(fh))


def link(url: str, text: str) -> str:
    if not url:
        return ""
    return f'<a href="{esc(url)}" rel="noopener">{esc(text)}</a>'


def t_utc(iso_text: str) -> str:
    if not iso_text:
        return ""
    shown = iso_text.replace("T", " ").replace("Z", " UTC")
    return f'<time datetime="{esc(iso_text)}" data-local>{esc(shown)}</time>'


def flag_links(codes: str) -> str:
    out = []
    for c in [c for c in (codes or "").split(";") if c]:
        out.append(f'<a class="flag" href="flagged.html#{esc(c)}">{esc(c)}</a>')
    return " ".join(out)


def bar(p_a: str, a: str, b: str) -> str:
    try:
        x = float(p_a)
    except (TypeError, ValueError):
        return ""
    return (f'<div class="bar" role="img" aria-label="{esc(a)} {x:.1f}% vs {esc(b)} {100 - x:.1f}%">'
            f'<span style="width:{x:.1f}%"></span></div>')


def prob_cell(p_a: str, p_b: str, a: str, b: str, url: str, label: str) -> str:
    if not p_a:
        return '<span class="blank">—</span>'
    fav_a = float(p_a) >= float(p_b)
    return (f'<div class="pp"><b class="{"fav" if fav_a else ""}">{esc(a)} {float(p_a):.1f}%</b>'
            f'<b class="{"fav" if not fav_a else ""}">{esc(b)} {float(p_b):.1f}%</b></div>'
            f'{bar(p_a, a, b)}<div class="src">{link(url, label)}</div>')


HEAD = """<!DOCTYPE html><html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>{title}</title><meta name="description" content="{desc}">
<link rel="stylesheet" href="style.css"></head><body>
<header class="top"><div class="wrap">
<a class="home" href="../index.html">← Home &amp; picks</a>
<nav aria-label="Secondary-market feed pages"><a href="index.html"{a1}>Lines</a><a href="flagged.html"{a2}>Flagged for Review</a><a href="method.html"{a3}>Method &amp; sources</a></nav>
</div></header><main class="wrap">"""

FOOT = """</main><footer class="wrap">Independent analysis, not affiliated with Hotspawn, Polymarket, bo3.gg or any
bookmaker. Not betting advice. Generated by <a href="{repo}/blob/main/feeds/build.py">feeds/build.py</a>
from <a href="{repo}/tree/main/feeds/data">feeds/data</a> · session <code>a0bdf924</code>.</footer>
<script>
document.querySelectorAll('time[data-local]').forEach(function(t){{
  var d=new Date(t.getAttribute('datetime')); if(isNaN(d)) return;
  t.title=t.textContent; t.textContent=d.toLocaleString([], {{weekday:'short', month:'short', day:'numeric', hour:'2-digit', minute:'2-digit'}});
}});
</script></body></html>"""


def page(title: str, desc: str, active: int, body: str) -> str:
    sel = ' aria-current="page"'
    return (HEAD.format(title=esc(title), desc=esc(desc), a1=sel if active == 1 else "",
                        a2=sel if active == 2 else "", a3=sel if active == 3 else "")
            + body + FOOT.format(repo=REPO_URL))


def build_index(summary: dict, fixtures: list[dict]) -> str:
    gen = summary.get("generated_utc") or ""
    tiles = [("Open CS2 matches on Hotspawn", summary.get("open_cs2_fixtures", 0)),
             ("Priced by a secondary source", summary.get("priced_any", 0)),
             ("Bookmaker quote (via bo3.gg)", summary.get("priced_bookmaker", 0)),
             ("Polymarket market", summary.get("priced_polymarket", 0)),
             ("Series format known", summary.get("format_known", 0))]
    tile_html = "".join(f'<div class="tile"><b>{esc(v)}</b><span>{esc(k)}</span></div>' for k, v in tiles)
    rows = []
    for r in fixtures:
        a, b = r["team_a"], r["team_b"]
        fav = r.get("secondary_favourite") or ""
        n_src = int(r.get("n_sources") or 0)
        basis = "mean of 2 sources" if n_src == 2 else "1 source"
        if fav:
            fav_pct = float(r["secondary_p_a_pct"] if fav == a else r["secondary_p_b_pct"])
            fav_html = (f'<div class="pick">Market favourite: <b>{esc(fav)}</b> {fav_pct:.1f}%'
                        f'<small>{basis}</small></div>')
        elif n_src:
            fav_html = (f'<div class="pick none">Even market (50/50) — no favourite'
                        f'<small>{basis}; see MF-14</small></div>')
        else:
            fav_html = '<div class="pick none">No secondary market found — blank, not inferred</div>'
        rows.append(f"""<tr id="f{esc(r['fixture_id'])}">
<td data-th="Match"><div class="m">{esc(a)} <i>vs</i> {esc(b)}</div>
<div class="sub">{esc(r['competition'])} · tier {esc((r['tier'] or '').upper())}</div>{fav_html}</td>
<td data-th="Kickoff">{t_utc(r['start_utc'])}<div class="sub">locks {t_utc(r['lock_utc'])}</div></td>
<td data-th="Format">{('BO' + esc(r['format_bo'])) if r['format_bo'] else '<span class="blank">—</span>'}<div class="sub">{esc(r['format_source'])}</div></td>
<td data-th="Bookmaker">{prob_cell(r['bookmaker_p_a_pct'], r['bookmaker_p_b_pct'], a, b, r['bookmaker_url'], (r['bookmaker_book'] or 'book') + ' (via bo3.gg)')}</td>
<td data-th="Polymarket">{prob_cell(r['polymarket_p_a_pct'], r['polymarket_p_b_pct'], a, b, r['polymarket_url'], 'Polymarket market')}</td>
<td data-th="Sources">{link(r['hotspawn_url'], 'Hotspawn')} {flag_links(r['flags'])}</td></tr>""")
    note_fallback = ""
    if summary.get("hotspawn_fallback"):
        note_fallback = ('<p class="warn">Hotspawn did not answer this run; the fixture list comes from '
                         f'{esc(summary["hotspawn_fallback"].get("path"))} (see MF-12).</p>')
    body = f"""<h1>Secondary betting lines for every open Hotspawn CS2 match</h1>
<p class="lead">Outside prices for the matches Pinnacle does not cover: the bookmaker quote that
<a href="https://bo3.gg/">bo3.gg</a> relays on its match pages, and <a href="https://polymarket.com/esports/cs2">Polymarket</a>
match-winner markets. Probabilities are de-vigged. Hotspawn crowd percentages are never used.</p>
<p class="callout"><b>Looking for the picks?</b> This page is a <b>data source</b> for the picks pages, not another picks board.
Start at the <a href="../index.html">home page</a>.</p>
{note_fallback}
<p class="stamp">Captured {t_utc(gen)} · refreshes hourly · <a href="{RUNS_URL}">refresh runs</a> ·
<a href="data/fixtures.csv">fixtures.csv</a> · <a href="data/market_feed.csv">market_feed.csv</a></p>
<section class="tiles" aria-label="Coverage">{tile_html}</section>
<div class="tablewrap"><table class="feed"><thead><tr><th>Match</th><th>Kickoff (your time)</th><th>Format</th>
<th>Bookmaker</th><th>Polymarket</th><th>Sources &amp; flags</th></tr></thead><tbody>
{''.join(rows) if rows else '<tr><td colspan="6">No open CS2 fixtures in the current Hotspawn capture.</td></tr>'}
</tbody></table></div>
<p class="small">A blank cell means the source does not list the match, or its quote failed a quality gate — see
<a href="flagged.html">Flagged for Review</a>. "Market favourite" is the plain mean of the de-vigged probabilities shown on the row,
from these secondary sources only; the site's picks pages combine it with primary prices and our own lines.</p>"""
    return page("Secondary betting lines · Hotspawn CS2", "De-vigged secondary-market probabilities for every open Hotspawn CS2 fixture.", 1, body)


def build_flagged(summary: dict, flags: list[dict], review: list[dict], codes: dict) -> str:
    by_code: dict[str, list[dict]] = {}
    for f in flags:
        by_code.setdefault(f["code"], []).append(f)
    sections = []
    for code in sorted(codes):
        items = by_code.get(code, [])
        rows = "".join(
            f"<tr><td data-th='Match'>{esc(f['match']) or '—'}<div class='sub'>{esc(f['fixture_id'])}</div></td>"
            f"<td data-th='Detail'>{esc(f['message'])}</td>"
            f"<td data-th='Links'>{link(f['source_url'], 'source')} {link(f['hotspawn_url'], 'Hotspawn')}</td></tr>"
            for f in items)
        sections.append(f"""<section id="{esc(code)}"><h2>{esc(code)} <span class="count">{len(items)}</span></h2>
<p class="sub">{esc(codes[code])}</p>
{'<div class="tablewrap"><table><thead><tr><th>Match</th><th>Detail</th><th>Links</th></tr></thead><tbody>' + rows + '</tbody></table></div>' if items else '<p class="small">None in this run.</p>'}
</section>""")
    rv = "".join(
        f"<tr><td data-th='Match'>{esc(r['team_a'])} vs {esc(r['team_b'])}<div class='sub'>{esc(r['fixture_id'])} · {t_utc(r['start_utc'])}</div></td>"
        f"<td data-th='Source'>{esc(r['source'])}: {esc(r['source_team_a'])} vs {esc(r['source_team_b'])}<div class='sub'>{esc(r['source_event'])}</div></td>"
        f"<td data-th='Kind'>{esc(r['kind'])}<div class='sub'>{esc(r['detail'])}</div></td>"
        f"<td data-th='Link'>{link(r['source_url'], 'source')}</td></tr>" for r in review)
    probes = "".join(
        f"<tr><td data-th='Source'>{esc(p.get('source'))}</td><td data-th='Status'>{esc(p.get('status'))} {esc(p.get('error') or '')}</td>"
        f"<td data-th='Link'>{link(p.get('url'), 'url')}</td></tr>" for p in summary.get("probes", []))
    body = f"""<h1>Flagged for Review</h1>
<p class="lead">Everything the feed could not confirm, with source links for manual review. Flagged items are published, never
silently resolved, and nothing here blocks the site. Capture {t_utc(summary.get('generated_utc') or '')}.</p>
{''.join(sections)}
<section id="review"><h2>Review list <span class="count">{len(review)}</span></h2>
<p class="sub">Source listings that were related to a Hotspawn fixture but not used (conflicting opponent, kickoff mismatch, failed quality gate).</p>
{'<div class="tablewrap"><table><thead><tr><th>Hotspawn fixture</th><th>Source listing</th><th>Why not used</th><th>Link</th></tr></thead><tbody>' + rv + '</tbody></table></div>' if review else '<p class="small">None in this run.</p>'}
</section>
<section id="probes"><h2>Reachability probes</h2><p class="sub">Fetched from the GitHub Actions runner; status only, nothing parsed into the feed.</p>
<div class="tablewrap"><table><thead><tr><th>Source</th><th>HTTP status</th><th>Link</th></tr></thead><tbody>{probes}</tbody></table></div></section>"""
    return page("Flagged for Review · secondary lines", "Unverified and conflicting items in the secondary-market feed.", 2, body)


def build_method(summary: dict) -> str:
    pages_rows = "".join(
        f"<tr><td data-th='Page'>{esc(p.get('page'))}</td><td data-th='Status'>{esc(p.get('status'))}</td>"
        f"<td data-th='CS2 rows'>{esc(p.get('cs2_rows'))}</td><td data-th='Fetched'>{t_utc(p.get('fetched_utc') or '')}</td>"
        f"<td data-th='Link'>{link(p.get('url'), 'page')}</td></tr>" for p in summary.get("hotspawn_pages", []))
    body = f"""<h1>Method &amp; sources</h1>
<h2>What this feed does</h2>
<ol class="steps">
<li><b>Hotspawn fixture list.</b> The pick'em pages <a href="https://play.hotspawn.com/cs2-pickems">/cs2-pickems</a>,
<a href="https://play.hotspawn.com/lobby">/lobby</a> and <a href="https://play.hotspawn.com/thp-pickems">/thp-pickems</a> are server-rendered
Angular pages; the full fixture list sits in the <code>&lt;script id="ng-state"&gt;</code> TransferState payload
(<code>scheduled_start_time</code>, <code>lock_time</code> as epoch milliseconds, team names, competition, tier). A fixture is open while
its <code>lock_time</code> is after the capture time. Only identity and timing fields are kept: crowd pick percentages are dropped
at parse time and can never reach this feed.</li>
<li><b>Polymarket.</b> Public Gamma API, series <code>10310</code> (<a href="https://gamma-api.polymarket.com/series?slug=counter-strike">"Counter Strike"</a>,
the daily CS2 match series): the event's <code>moneyline</code> market gives both teams' share prices, best bid/ask, spread, book depth and volume.
Prices of the two complementary outcomes are normalised to 100%. A quote is <b>not used</b> if the market is closed, live, not accepting orders,
has a spread above 0.10 (Polymarket then displays the last trade instead of the midpoint), less than $100 of depth, or degenerate prices.</li>
<li><b>Bookmaker quote via bo3.gg.</b> bo3.gg's public API (<code>api.bo3.gg/api/v1/matches</code>, the JSON its own pages load) lists every
upcoming CS2 match with its series format (<code>bo_type</code>) and, where available, a bookmaker's live match-winner odds in
<code>bet_updates</code> (provider name and the bookmaker's own match URL). Decimal odds are de-vigged multiplicatively:
p = (1/odds) / Σ(1/odds). Suspended quotes, odds ≤ 1.00 and margins outside −2%…20% are not used. The price is a relay, so the bookmaker's
match URL is linked on every row for manual checking (flag MF-09).</li>
<li><b>Matching.</b> A source listing is attached to a Hotspawn fixture only if at least one team name matches exactly (case, accents,
punctuation, a leading "Team" or trailing "Esports/Gaming/Team/Club/Clan" ignored, or an evidence-linked alias in
<a href="{REPO_URL}/blob/main/feeds/aliases.json">aliases.json</a>) and the other team is also exact (kickoff within 60 min) or a recognisable
variant of the same name (substring or initials) with the kickoff within 15 min. Same team against a different opponent at the same kickoff is
published as a conflict (MF-02) and not used.</li>
<li><b>Output.</b> One row per open fixture with each source's de-vigged probability and link, the series format and the flags.
"Market favourite" is the plain mean of the probabilities on the row. Nothing is filled in: no listing → blank + MF-01.</li>
</ol>
<h2>Refresh</h2>
<p>GitHub Actions workflow <a href="{RUNS_URL}">feed-a0bdf924.yml</a> runs hourly, on code changes and on demand. It collects, joins, builds, runs
<a href="{REPO_URL}/blob/main/feeds/tests.py">feeds/tests.py</a> and commits only if every test passes. If Hotspawn cannot be read and no
committed fixture list exists, the run publishes nothing (last good data stays up). A market source that fails leaves its column blank (MF-11).</p>
<h2>Hotspawn pages read in this capture</h2>
<div class="tablewrap"><table><thead><tr><th>Page</th><th>HTTP</th><th>CS2 rows</th><th>Fetched</th><th>Link</th></tr></thead><tbody>{pages_rows}</tbody></table></div>
<h2>Data files</h2>
<ul class="plain"><li><a href="data/fixtures.csv">data/fixtures.csv</a> — one row per open Hotspawn CS2 fixture</li>
<li><a href="data/market_feed.csv">data/market_feed.csv</a> — one row per accepted source quote (prices, implied and de-vigged %, overround, depth, links)</li>
<li><a href="data/review.csv">data/review.csv</a> — listings related to a fixture but not used, with the reason</li>
<li><a href="data/flags.csv">data/flags.csv</a> · <a href="data/summary.json">data/summary.json</a> · <a href="data/capture.json">data/capture.json</a> (HTTP status, bytes and SHA-256 of every response)</li>
<li>Archived trimmed responses: <a href="{REPO_URL}/tree/main/feeds/data/raw">data/raw/</a> — the tests re-derive every published number from them.</li></ul>
<h2>Limits, stated plainly</h2>
<ul class="plain"><li>Secondary sources cover what they list: low-tier matches can be absent from both. Those rows stay blank and are flagged.</li>
<li>Polymarket books on small matches can be thin; depth, volume and spread are published per row in market_feed.csv.</li>
<li>The bookmaker price is read through bo3.gg's relay; the bookmaker's own page is linked but may refuse automated reads (see the probes on the Flagged page).</li>
<li>Kickoff times on Hotspawn are scheduled times; real start times can slip.</li></ul>"""
    return page("Method & sources · secondary lines", "How the secondary-market feed is collected, matched and de-vigged.", 3, body)


def main() -> int:
    summary = json.loads((DATA / "summary.json").read_text(encoding="utf-8"))
    codes = json.loads((DATA / "flag_codes.json").read_text(encoding="utf-8"))
    fixtures = read_csv("fixtures.csv")
    flags = read_csv("flags.csv")
    review = read_csv("review.csv")
    (HERE / "index.html").write_text(build_index(summary, fixtures), encoding="utf-8")
    (HERE / "flagged.html").write_text(build_flagged(summary, flags, review, codes), encoding="utf-8")
    (HERE / "method.html").write_text(build_method(summary), encoding="utf-8")
    print(f"build: index ({len(fixtures)} rows), flagged ({len(flags)} flags, {len(review)} review rows), method")
    return 0


if __name__ == "__main__":
    sys.exit(main())
